"""Plots, tables and flip excerpts from results/runs.

    python scripts/analyze.py                 # plots + tables + excerpts
    python scripts/analyze.py --judge         # also run the comprehension judge (costs money)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from swarm import analysis  # noqa: E402
from swarm.config import REPO_ROOT  # noqa: E402


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results-dir", type=Path, default=REPO_ROOT / "results")
    p.add_argument("--judge", action="store_true", help="judge every honest turn of un-instructed runs, plus a calibration sample of explicit runs")
    p.add_argument("--judge-sample", type=int, default=20, help="explicit-rule calibration sample size (turns)")
    p.add_argument("--rejudge", action="store_true", help="re-run the judge on runs that already have judge output")
    p.add_argument("--client", choices=["live", "fake"], default="live")
    a = p.parse_args()

    runs_dir = a.results_dir / "runs"
    runs = analysis.load_runs(runs_dir)
    print(f"{len(runs)} complete runs")
    if not runs:
        return

    if a.judge:
        from swarm.judge import judge_run
        from swarm.llm import make_client

        client = make_client(a.client)
        un = [r for r in runs if r.config.rule == "uninstructed"]
        for r in un:
            if a.rejudge or not (r.run_dir / "judge.jsonl").exists():
                out = judge_run(client, r.config.judge_model, r.run_dir)
                print(f"judged {r.run_dir.name}: {len(out['records'])} turns, ${out['usage_totals']['cost_usd']:.2f}")
        ex = [r for r in runs if r.config.rule == "explicit" and r.config.n_bad >= 1]
        if ex and (a.rejudge or not any((r.run_dir / "judge_sample.jsonl").exists() for r in ex)):
            out = judge_run(client, ex[0].config.judge_model, ex[0].run_dir, sample=a.judge_sample)
            print(f"judged calibration sample {ex[0].run_dir.name}: {len(out['records'])} turns, ${out['usage_totals']['cost_usd']:.2f}")

    # Never pool models or problem sets: one set of tables and plots per (swarm model, problem set).
    for model, pset in sorted({(r.config.model, r.config.problem_set) for r in runs}):
        mruns = [r for r in runs if (r.config.model, r.config.problem_set) == (model, pset)]
        label = model if pset == "calibrated" else f"{model}-{pset}"
        tables = a.results_dir / "tables" / label
        tables.mkdir(parents=True, exist_ok=True)
        md = f"# Results summary: `{label}`\n\nGenerated by `scripts/analyze.py` from complete runs in `results/runs/`. "
        md += "Early-stopped runs carry their final cumulative value forward.\n\n"
        md += analysis.summary_markdown(analysis.summary_rows(mruns))
        comp = analysis.comprehension_rows(mruns) + analysis.comprehension_rows(mruns, "judge_sample.jsonl")
        if comp:
            md += "\n## Comprehension judge\n\n" + analysis.comprehension_markdown(comp)
        (tables / "summary.md").write_text(md)
        print(md)

        excerpts = [e for r in mruns for e in analysis.find_flip_excerpts(r)]
        ex_md = f"# Flip excerpts: `{label}` (candidates; choose by hand for the README)\n\n"
        ex_md += "\n".join(analysis.format_excerpt(e) for e in excerpts) if excerpts else "No honest agent defected in any run.\n"
        (tables / "flip_excerpts.md").write_text(ex_md)
        print(f"{len(excerpts)} flip excerpts -> {tables / 'flip_excerpts.md'}")

        for path in analysis.make_plots(mruns, a.results_dir / "plots" / label, model_label=label):
            print(f"wrote {path}")


if __name__ == "__main__":
    main()
